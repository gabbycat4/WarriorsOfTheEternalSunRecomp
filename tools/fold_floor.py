#!/usr/bin/env python3
"""fold_floor.py - turn interpreter-floor evidence into validated routine roots.

Same rules as RocketKnightAdventuresRecomp/tools/fold_floor_coverage.py, but
decoding with the recompiler's own decoder (tools/m68k_runs.c), so it needs no
disassembler library. A floor address becomes a [functions] late_extra root
only when ALL hold:
  * it is a ROM address and not already a generated function entry;
  * the interpreter-only runs (coverage/*.txt) executed it as an instruction start;
  * every instruction from it to the first branch/jump/call/return decodes
    cleanly and was executed too (alignment proof);
  * it is not inside an existing generated function's address span (a new root
    there would cut the parent function in two).
late_extra roots are non-recursive: they cannot reopen heuristic discovery.
Usage:
  python3 tools/fold_floor.py --rom game/wotes.bin --generated build/generated/wotes \
      --floor 'evidence/*/floor_coverage*.toml' --oracle 'coverage/*.txt' \
      --out game/wotes_floor_fold.discovery.toml
Gate every regeneration with tools/compare_native.py (nothing native may be lost).
"""
import argparse, glob, os, re, subprocess, sys
from pathlib import Path

ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
ap.add_argument('--rom', required=True)
ap.add_argument('--generated', required=True, type=Path)
ap.add_argument('--floor', nargs='+', required=True)
ap.add_argument('--oracle', nargs='+', required=True)
ap.add_argument('--out', required=True, type=Path)
ap.add_argument('--runs-tool', default=os.path.join(os.path.dirname(__file__), 'm68k_runs'))
a = ap.parse_args()

def files(pats):
    out = []
    for p in pats:
        out += sorted(glob.glob(p))
    return out

rom_size = os.path.getsize(a.rom)

# Generated functions: entries and instruction spans.
starts, spans = set(), []
for f in a.generated.glob('*_part*.c'):
    text = f.read_text()
    for m in re.finditer(r'^void func_([0-9A-F]{6})\(void\) \{(.*?)^\}', text, re.M | re.S):
        s = int(m[1], 16)
        starts.add(s)
        ins = [int(x, 16) for x in re.findall(r'/\* \$([0-9A-F]{6}) \*/', m[2])]
        if ins:
            spans.append((s, max(ins)))
def inside_span(x):
    return any(s < x <= e for s, e in spans)

floor = {}
for f in files(a.floor):
    for m in re.finditer(r'^\s*0x([0-9A-Fa-f]+),\s*#?(.*)$', open(f).read(), re.M):
        floor.setdefault(int(m[1], 16), f'{os.path.basename(f)}: {m[2].strip()}')
oracle = set()
for f in files(a.oracle):
    for l in open(f):
        l = l.strip()
        if l and not l.startswith('#'):
            oracle.add(int(l.split()[0], 16))

cands = sorted(x for x in floor if x < rom_size)
res = subprocess.run([a.runs_tool, a.rom], input=''.join('%06X\n' % x for x in cands),
                     capture_output=True, text=True, check=True).stdout.split('\n')
runs = {}
for line in res:
    p = line.split()
    if len(p) >= 2:
        runs[int(p[0], 16)] = (p[1] == 'ok', [tuple(t.split(':')) for t in p[2:]])

acc, rej = [], []
for x in cands:
    ok, ins = runs.get(x, (False, []))
    if x in starts:                 rej.append((x, 'already a function')); continue
    if x not in oracle:             rej.append((x, 'not seen by the interpreter runs yet')); continue
    if not ok:                      rej.append((x, 'does not decode cleanly')); continue
    unseen = [t[0] for t in ins if int(t[0], 16) not in oracle]
    if unseen:                      rej.append((x, 'run not fully executed (%s)' % unseen[0])); continue
    if inside_span(x):              rej.append((x, 'inside an existing function')); continue
    acc.append(x)

with open(a.out, 'w') as f:
    f.write('# Generated by tools/fold_floor.py - validated interpreter-floor roots.\n')
    f.write('# Each: executed by the interpreter, clean straight-line decode, not inside a\n')
    f.write('# generated function. Non-recursive late_extra roots.\n[functions]\nlate_extra = [\n')
    for x in acc:
        f.write('  0x%06X,  # %s\n' % (x, floor[x]))
    f.write(']\n')
print('floor addresses %d: accepted %d, rejected %d -> %s' % (len(cands), len(acc), len(rej), a.out))
from collections import Counter
for why, n in Counter(r[1].split(' (')[0] for r in rej).most_common():
    print('  rejected: %-40s %d' % (why, n))
